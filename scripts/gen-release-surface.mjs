#!/usr/bin/env node
// P70.F1 · F2 · F4 — release surface generation.
//
// Everything a release publishes that is *derived* rather than authored comes
// from here, so the version can only be stated once:
//
//   release-notes-<version>.md   F4 — assembled from the newest SPEC-CHANGELOG
//                                entry plus the TODO rows closed in it
//   winget manifests             F2 — the Windows-first package-manager route
//                                (version + installer URL + SHA-256 slot)
//   SHA256SUMS                   F1 — checksums over the produced artifacts
//
// The version authority is `src-tauri/tauri.conf.json` (P70.A7). A release
// driver runs this after bundling:
//
//   node scripts/gen-release-surface.mjs --artifacts <bundle-dir> --out dist/release
//
// `--check` is the CI mode: it verifies the committed winget manifest still
// names the authoritative version, which is what stops the public surface from
// drifting from the binary.
//
// 2026-09-26: the F3 download-page check retired — `docs/download.md` was
// archived with the v0 corpus and is re-authored with the v1 release surface.

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

const argv = process.argv.slice(2);
const opt = (name) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
};
const CHECK = argv.includes('--check');
const OUT = resolve(ROOT, opt('--out') ?? 'dist/release');
const ARTIFACTS = opt('--artifacts');

const conf = JSON.parse(readFileSync(resolve(ROOT, 'src-tauri/tauri.conf.json'), 'utf8'));
const VERSION = conf.version;
const ID = conf.identifier;
const PRODUCT = conf.productName;
const problems = [];
const fail = (m) => problems.push(m);

// ---------------------------------------------------------------- F2 winget
// One manifest set, three files — the shape `winget publish` consumes. The
// installer URL follows the release asset naming tauri-action produces.
const WINGET_DIR = 'packaging/winget';
const installerFor = (arch) => ({
  Arch: arch,
  Url: `https://github.com/sarv-projects/AgentCowork/releases/download/v${VERSION}/${PRODUCT}_${VERSION}_${arch === 'x64' ? 'x64' : 'arm64'}-setup.exe`,
  Sha256: '<filled by the release workflow from SHA256SUMS>',
});

function wingetManifests() {
  const base = {
    PackageIdentifier: 'EveryAIOS.EveryAIOS',
    PackageVersion: VERSION,
    PackageLocale: 'en-US',
    Publisher: conf.bundle?.publisher ?? 'AgentCowork',
    PackageName: PRODUCT,
    License: conf.bundle?.license ?? 'MIT OR Apache-2.0',
    ShortDescription: conf.bundle?.shortDescription ?? 'A local-first desktop cockpit for governed AI agents.',
    PackageUrl: conf.bundle?.homepage ?? 'https://github.com/sarv-projects/AgentCowork',
    InstallerType: 'nullsoft',
    Scope: 'user',
    Installers: [installerFor('x64'), installerFor('arm64')],
  };
  return {
    'EveryAIOS.EveryAIOS.installer.yaml': [
      '# Generated by scripts/gen-release-surface.mjs — do not edit by hand.',
      'PackageIdentifier: EveryAIOS.EveryAIOS',
      `PackageVersion: ${VERSION}`,
      'InstallerType: nullsoft',
      'Scope: user',
      'Installers:',
      ...base.Installers.flatMap((i) => [
        `  - Architecture: ${i.Arch}`,
        `    InstallerUrl: ${i.Url}`,
        `    InstallerSha256: ${i.Sha256}`,
      ]),
      '',
    ].join('\n'),
    'EveryAIOS.EveryAIOS.locale.en-US.yaml': [
      '# Generated by scripts/gen-release-surface.mjs — do not edit by hand.',
      'PackageIdentifier: EveryAIOS.EveryAIOS',
      `PackageVersion: ${VERSION}`,
      'PackageLocale: en-US',
      `Publisher: ${base.Publisher}`,
      `PackageName: ${PRODUCT}`,
      `License: ${base.License}`,
      `ShortDescription: ${base.ShortDescription}`,
      `PackageUrl: ${base.PackageUrl}`,
      '',
    ].join('\n'),
    'EveryAIOS.EveryAIOS.yaml': [
      '# Generated by scripts/gen-release-surface.mjs — do not edit by hand.',
      'PackageIdentifier: EveryAIOS.EveryAIOS',
      `PackageVersion: ${VERSION}`,
      'DefaultLocale: en-US',
      'ManifestType: version',
      'ManifestVersion: 1.6.0',
      '',
    ].join('\n'),
  };
}

// ---------------------------------------------------------------- F4 notes
/** The newest changelog entry, verbatim — the release notes are the entry. */
function newestChangelogEntry() {
  const text = readFileSync(resolve(ROOT, 'SPEC-CHANGELOG.md'), 'utf8');
  const start = text.indexOf('\n## v');
  if (start < 0) return null;
  const rest = text.slice(start + 1);
  const end = rest.indexOf('\n---\n', 4);
  const entry = end > 0 ? rest.slice(0, end) : rest;
  const heading = entry.split('\n')[0];
  return { heading, body: entry.slice(heading.length).trim() };
}

/** TODO rows whose marker names this changelog revision or a v4.xx tag. */
function closedRowsFor(revision) {
  const todo = readFileSync(resolve(ROOT, 'TODO.md'), 'utf8');
  const rows = [];
  for (const line of todo.split('\n')) {
    const m = /^- \[x\] `\[[^\]]*?\]` \*\*(P[\d.]+[\w]* — [^*]+)\*\*/.exec(line);
    if (m) rows.push(m[1].trim());
  }
  return rows;
}

function releaseNotes() {
  const entry = newestChangelogEntry();
  const revision = entry?.heading?.match(/## (v[\d.]+)/)?.[1] ?? 'unreleased';
  const closed = closedRowsFor(revision);
  return [
    `# ${PRODUCT} v${VERSION} — release notes`,
    '',
    `> Generated by \`scripts/gen-release-surface.mjs\` from \`SPEC-CHANGELOG.md\` (${revision}) — do not edit by hand.`,
    '',
    '## What changed',
    '',
    entry?.body ?? '_(no changelog entry found)_',
    '',
    '## Delivery rows closed',
    '',
    `This revision carries **${closed.length}** checked rows in \`TODO.md\`; the authoritative per-row state (including every`,
    '`[IMPLEMENTED — unverified]` residual) lives there — the markers are not summarised away here.',
    '',
    '## Verify this download',
    '',
    '- checksums: `SHA256SUMS` in the release assets;',
    '- signature: see `docs/signing.md` (Authenticode + the updater minisign key) and `docs/updating.md` §1;',
    '- support scope: `SUPPORT-MATRIX.md` — v1 is Windows-first and not yet qualified on a real host (`P70.E8`).',
    '',
    '## Honest status',
    '',
    '`node scripts/release-qualify.mjs` is the release gate. Its `BLOCKED` items are printed in every run and are not',
    'converted into passes: an install on a clean Windows host, the upgrade/rollback drill and the live soaks are',
    'outstanding until a candidate has actually executed them.',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- F1 sums
function sha256Sums(dir) {
  const lines = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (!name.endsWith('.sig') && !name.endsWith('.json')) {
        lines.push(`${createHash('sha256').update(readFileSync(p)).digest('hex')}  ${basename(p)}`);
      }
    }
  };
  walk(dir);
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- run
if (CHECK) {
  // The committed surface must name the authoritative version.
  for (const [name, body] of Object.entries(wingetManifests())) {
    const p = resolve(ROOT, WINGET_DIR, name);
    if (!existsSync(p)) {
      fail(`F2: ${WINGET_DIR}/${name} is missing (generate it: node scripts/gen-release-surface.mjs)`);
      continue;
    }
    const ref = /PackageVersion:\s*(\S+)/.exec(body)?.[1];
    const got = /PackageVersion:\s*(\S+)/.exec(readFileSync(p, 'utf8'))?.[1];
    if (ref !== got) fail(`F2: ${name} declares v${got}, the app is v${ref}`);
  }
  // 2026-09-26: F3 (docs/download.md existence/version/sections) retired with
  // the v0 corpus; the download page is re-authored with the v1 release surface.
  if (problems.length) {
    console.error('release-surface: FAIL');
    for (const p of problems) console.error(`  ✗ ${p}`);
    process.exit(1);
  }
  console.log(`release-surface: ok (winget manifests name v${VERSION})`);
  process.exit(0);
}

// Generation mode.
mkdirSync(OUT, { recursive: true });
for (const [name, body] of Object.entries(wingetManifests())) {
  mkdirSync(resolve(ROOT, WINGET_DIR), { recursive: true });
  writeFileSync(resolve(ROOT, WINGET_DIR, name), body);
}
writeFileSync(resolve(OUT, `release-notes-${VERSION}.md`), releaseNotes());
if (ARTIFACTS) {
  if (!existsSync(ARTIFACTS)) {
    console.error(`release-surface: artifacts dir not found: ${ARTIFACTS}`);
    process.exit(1);
  }
  writeFileSync(resolve(OUT, 'SHA256SUMS'), sha256Sums(resolve(ARTIFACTS)));
} else {
  console.log('release-surface: no --artifacts dir — checksums not produced (nothing to measure)');
}
console.log(`release-surface: wrote winget manifests (${WINGET_DIR}) + release-notes-${VERSION}.md in ${OUT}`);
